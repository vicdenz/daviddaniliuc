-- Private practice data. Only trusted server code may use the service role.
create table if not exists public.prep_problems (
  id text primary key,
  payload jsonb not null
);

create table if not exists public.prep_cases (
  id text primary key,
  problem_id text not null references public.prep_problems(id),
  payload jsonb not null,
  deleted boolean not null default false,
  edited boolean not null default false
);
create index if not exists prep_cases_problem_id_idx on public.prep_cases(problem_id);

create table if not exists public.prep_artifacts (
  id text primary key,
  problem_id text not null references public.prep_problems(id),
  path text not null,
  hash text not null,
  content text not null
);
create index if not exists prep_artifacts_problem_id_idx on public.prep_artifacts(problem_id);

create table if not exists public.prep_work (
  problem_id text not null references public.prep_problems(id),
  language text not null,
  code text not null,
  updated timestamptz not null default now(),
  primary key (problem_id, language)
);

create table if not exists public.prep_progress (
  problem_id text primary key references public.prep_problems(id),
  notes text not null default '',
  status text not null default 'todo',
  updated timestamptz not null default now()
);

create table if not exists public.prep_submissions (
  id bigint generated by default as identity primary key,
  problem_id text not null references public.prep_problems(id),
  language text,
  code text,
  mode text,
  result jsonb,
  created timestamptz not null default now()
);
create index if not exists prep_submissions_problem_id_idx on public.prep_submissions(problem_id);

create table if not exists public.prep_auth_sessions (
  token_hash text primary key,
  password_version text not null,
  expires bigint not null
);

create table if not exists public.prep_auth_attempts (
  client text primary key,
  failures integer not null,
  reset_at bigint not null
);

revoke all on public.prep_problems, public.prep_cases, public.prep_artifacts,
  public.prep_work, public.prep_progress, public.prep_submissions,
  public.prep_auth_sessions, public.prep_auth_attempts from anon, authenticated;
revoke all on sequence public.prep_submissions_id_seq from anon, authenticated;

alter table public.prep_problems enable row level security;
alter table public.prep_cases enable row level security;
alter table public.prep_artifacts enable row level security;
alter table public.prep_work enable row level security;
alter table public.prep_progress enable row level security;
alter table public.prep_submissions enable row level security;
alter table public.prep_auth_sessions enable row level security;
alter table public.prep_auth_attempts enable row level security;

grant select, insert, update, delete on public.prep_problems, public.prep_cases,
  public.prep_artifacts, public.prep_work, public.prep_progress,
  public.prep_submissions, public.prep_auth_sessions,
  public.prep_auth_attempts to service_role;
grant usage, select on sequence public.prep_submissions_id_seq to service_role;
