alter table public.prep_cases add column position bigint generated by default as identity;

create view public.prep_case_summaries with (security_invoker = true) as
select id, problem_id, position, deleted,
  payload - 'input' - 'expected' - 'growthInput' - 'growthExpected' as payload
from public.prep_cases;
create view public.prep_case_counts with (security_invoker = true) as
select problem_id, count(*)::integer as count from public.prep_cases where not deleted group by problem_id;
revoke all on public.prep_case_summaries, public.prep_case_counts from anon, authenticated;
grant select on public.prep_case_summaries, public.prep_case_counts to service_role;
grant usage, select on sequence public.prep_cases_position_seq to service_role;

