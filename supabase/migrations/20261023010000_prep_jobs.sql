create function public.prep_login_attempt(client_key text) returns boolean
language plpgsql security definer set search_path = public as $$
declare attempts integer; now_ms bigint := (extract(epoch from clock_timestamp()) * 1000)::bigint;
begin
  insert into public.prep_auth_attempts(client, failures, reset_at) values(client_key, 1, now_ms + 900000)
  on conflict(client) do update set
    failures = case when prep_auth_attempts.reset_at <= now_ms then 1 else prep_auth_attempts.failures + 1 end,
    reset_at = case when prep_auth_attempts.reset_at <= now_ms then now_ms + 900000 else prep_auth_attempts.reset_at end
  returning failures into attempts;
  return attempts <= 5;
end; $$;
revoke all on function public.prep_login_attempt(text) from public, anon, authenticated;
grant execute on function public.prep_login_attempt(text) to service_role;
